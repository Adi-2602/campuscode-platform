/**
 * Get teacher's teaching load summary
 */
const getTeacherLoadSummary = async (teacherId) => {
  const classes = await Class.find({
    $or: [
      { mainFaculty: teacherId },
      { coFaculties: teacherId }
    ]
  }).lean();

  const asMainFaculty = classes.filter(
    cls => cls.mainFaculty?.toString() === teacherId.toString()
  ).length;

  const asCoFaculty = classes.filter(
    cls => cls.coFaculties?.some(cf => cf.toString() === teacherId.toString())
  ).length;

  // Calculate total weekly hours
  let totalMinutes = 0;
  classes.forEach(cls => {
    totalMinutes += cls.labDuration || 0;
  });

  const hours = Math.floor(totalMinutes / 60);
  const minutes = totalMinutes % 60;

  // Get unique batches and sections
  const uniqueBatches = [...new Set(classes.map(cls => cls.batch))];
  const uniqueSections = [...new Set(classes.map(cls => cls.section))];

  return {
    totalClasses: classes.length,
    asMainFaculty,
    asCoFaculty,
    weeklyHours: {
      total: totalMinutes,
      hours,
      minutes,
      formatted: `${hours}h ${minutes}m`
    },
    uniqueBatches: uniqueBatches.length,
    uniqueSections: uniqueSections.length,
    batches: uniqueBatches.sort(),
    sections: uniqueSections.sort()
  };
};

